#!/usr/bin/env python3
"""Rewrite GCC multi-character constants in one OpenCE file.

GCC packs 'head' as 0x68656164 on both x86 and PowerPC. Halo cache files
store that signature as the bytes h,e,a,d, which a little-endian load reads
as 0x64616568. OpenCE compares those with the character constants, so the
PowerPC (and host GCC) build must use the little-endian values or
cache_file_identify never recognizes a map.

Only character constants of length 4 are rewritten. String literals are
left alone. The generated file is a build product.
"""

import sys


def little_endian_fourcc(text):
    value = (
        ord(text[0])
        | (ord(text[1]) << 8)
        | (ord(text[2]) << 16)
        | (ord(text[3]) << 24)
    )
    return "0x%08xu" % value


def rewrite(source):
    out = []
    i = 0
    n = len(source)
    while i < n:
        if source[i] == '"':
            j = i + 1
            while j < n:
                if source[j] == "\\":
                    j += 2
                    continue
                if source[j] == '"':
                    j += 1
                    break
                j += 1
            out.append(source[i:j])
            i = j
            continue
        if source[i] == "'":
            j = i + 1
            chars = []
            escaped = False
            while j < n and source[j] != "'":
                if source[j] == "\\":
                    escaped = True
                    break
                chars.append(source[j])
                j += 1
            if (
                not escaped
                and j < n
                and source[j] == "'"
                and len(chars) == 4
            ):
                out.append(little_endian_fourcc("".join(chars)))
                i = j + 1
                continue
        out.append(source[i])
        i += 1
    return "".join(out)


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: le_fourcc.py input.c output.c\n")
        return 2
    with open(sys.argv[1], "r", encoding="utf-8", newline="") as handle:
        source = handle.read()
    banner = (
        "/* Generated by tools/le_fourcc.py from OpenCE cache_file_formats.c.\n"
        "   Four-character constants are the little-endian file values.\n"
        "   Do not edit. AGPL-3.0-or-later, same as the OpenCE source. */\n"
    )
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as handle:
        handle.write(banner)
        handle.write(rewrite(source))
        if not source.endswith("\n"):
            handle.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
